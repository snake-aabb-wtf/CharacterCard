def _fix_quotes(obj):
    if isinstance(obj, str):
        return obj.replace("「", "“").replace("」", "”").replace("『", "‘").replace("』", "’")
    if isinstance(obj, list):
        return [_fix_quotes(x) for x in obj]
    if isinstance(obj, dict):
        return {k: _fix_quotes(v) for k, v in obj.items()}
    return obj

